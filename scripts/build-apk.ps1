# Builds a universal release APK for Wallnut and copies it next to the repo.
#
#   powershell -ExecutionPolicy Bypass -File scripts/build-apk.ps1
#
# Requirements:
#   * JDK 17 (Temurin/Zulu)                  -> .toolchain\<jdk folder>
#   * Android SDK command-line tools         -> C:\Android\Sdk
# The script is idempotent: it reuses an existing keystore and Gradle cache.

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$toolchain = Join-Path $env:USERPROFILE '.toolchain'
$jdkHome = Get-ChildItem -Path $toolchain -Directory -Filter '*jdk*' -ErrorAction SilentlyContinue | Select-Object -First 1
$sdkHome = 'C:\Android\Sdk'

if (-not $jdkHome) { throw "JDK not found in $toolchain. Extract a JDK 17 there first." }
if (-not (Test-Path $sdkHome)) { throw "Android SDK not found in $sdkHome." }

$env:JAVA_HOME = $jdkHome.FullName
$env:ANDROID_HOME = $sdkHome
$env:ANDROID_SDK_ROOT = $sdkHome
$env:Path = "$($jdkHome.FullName)\bin;$sdkHome\platform-tools;$sdkHome\cmdline-tools\latest\bin;$env:Path"

Write-Host "JAVA_HOME    $env:JAVA_HOME"
Write-Host "ANDROID_HOME $env:ANDROID_HOME"

# Native tools (java, keytool, gradle) write progress to stderr. PowerShell's
# 'Stop' preference turns that into a fatal error, so relax it around them.
$ErrorActionPreference = 'Continue'
& "$env:JAVA_HOME\bin\java" -version
$ErrorActionPreference = 'Stop'

$androidDir = Join-Path $root 'android'
$keystore = Join-Path $androidDir 'app\wallnut-release.keystore'
$propsPath = Join-Path $androidDir 'gradle.properties'

if (-not (Test-Path $keystore)) {
  Write-Host "Generating release keystore..."
  $ErrorActionPreference = 'Continue'
  & "$env:JAVA_HOME\bin\keytool" -genkeypair -v `
    -keystore $keystore -alias wallnut -keyalg RSA -keysize 2048 -validity 10000 `
    -storepass wallnut-release -keypass wallnut-release `
    -dname "CN=Wallnut, OU=Personal, O=Wallnut, L=Bengaluru, S=Karnataka, C=IN"
  $ErrorActionPreference = 'Stop'
}

$props = Get-Content $propsPath -Raw
if ($props -notmatch 'WALLNUT_STORE_FILE') {
  Add-Content -Path $propsPath -Value @'

# Release signing for personal builds (generated by scripts/build-apk.ps1).
# Keep these values if you want future builds to update the installed app.
WALLNUT_STORE_FILE=wallnut-release.keystore
WALLNUT_KEY_ALIAS=wallnut
WALLNUT_STORE_PASSWORD=wallnut-release
WALLNUT_KEY_PASSWORD=wallnut-release
'@
  Write-Host "Added signing properties to gradle.properties"
}

$appGradlePath = Join-Path $androidDir 'app\build.gradle'
$appGradle = Get-Content $appGradlePath -Raw

if ($appGradle -notmatch 'WALLNUT_STORE_FILE') {
  # Add a release signing config next to the debug one (literal, unique match).
  $anchor = "    signingConfigs {`r`n        debug {"
  if (-not $appGradle.Contains($anchor)) { $anchor = "    signingConfigs {`n        debug {" }
  if (-not $appGradle.Contains($anchor)) { throw "Could not find the signingConfigs block to patch." }

  $replacement = @"
    signingConfigs {
        // Personal release signing - values live in gradle.properties.
        release {
            storeFile file(WALLNUT_STORE_FILE)
            storePassword WALLNUT_STORE_PASSWORD
            keyAlias WALLNUT_KEY_ALIAS
            keyPassword WALLNUT_KEY_PASSWORD
        }
        debug {
"@
  $appGradle = $appGradle.Replace($anchor, $replacement)

  # Point the release build type at the new signing config.
  $releaseAnchor = "            signingConfig signingConfigs.debug`r`n            def enableShrinkResources"
  if (-not $appGradle.Contains($releaseAnchor)) {
    $releaseAnchor = "            signingConfig signingConfigs.debug`n            def enableShrinkResources"
  }
  if (-not $appGradle.Contains($releaseAnchor)) { throw "Could not find the release buildType to patch." }
  $appGradle = $appGradle.Replace($releaseAnchor, "            signingConfig signingConfigs.release`r`n            def enableShrinkResources")

  Set-Content -Path $appGradlePath -Value $appGradle -NoNewline
  Write-Host "Wired release signing into app/build.gradle"
}

Push-Location $androidDir
try {
  # Prefer a manually installed Gradle 9.3.1: the wrapper's downloader has a
  # 10-second read timeout that flaky connections trip, leaving a partial zip.
  $manualGradle = Join-Path $toolchain 'gradle-9.3.1\bin\gradle.bat'
  $gradleCmd = if (Test-Path $manualGradle) { $manualGradle } else { Join-Path $androidDir 'gradlew.bat' }
  Write-Host ""
  Write-Host "Building universal release APK (arm64-v8a + armeabi-v7a) with $gradleCmd"
  Write-Host ""
  & $gradleCmd assembleRelease '-PreactNativeArchitectures=arm64-v8a,armeabi-v7a' --no-daemon
  if ($LASTEXITCODE -ne 0) { throw "Gradle build failed with exit code $LASTEXITCODE" }
} finally {
  Pop-Location
}

$apk = Join-Path $androidDir 'app\build\outputs\apk\release\app-release.apk'
if (-not (Test-Path $apk)) { throw "APK not found at $apk" }

$target = Join-Path $root ("wallnut-" + (Get-Date -Format 'yyyy-MM-dd') + ".apk")
Copy-Item -Force $apk $target
$size = [Math]::Round((Get-Item $target).Length / 1MB, 1)
Write-Host ""
Write-Host "APK ready: $target ($size MB)"
Write-Host "Install with: adb install -r `"$target`"  - or copy it to your phone and tap it."

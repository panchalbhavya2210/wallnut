// Bundles drizzle migration SQL into a TypeScript module.
// Rationale: Metro's default transformer handles expo-sqlite's web worker and
// wasm assets correctly, and overriding it to get `.sql` imports to work
// breaks web bundling. Generating a TS module with the SQL inlined keeps the
// default pipeline untouched — migrations stay the single source of truth
// (drizzle-kit still generates the .sql files and we read them here).
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const migrationsDir = join(root, 'src', 'db', 'migrations');
const journalPath = join(migrationsDir, 'meta', '_journal.json');

if (!existsSync(journalPath)) {
  console.error('No migrations found. Run `npx drizzle-kit generate` first.');
  process.exit(1);
}

const journal = JSON.parse(readFileSync(journalPath, 'utf8'));
const files = readdirSync(migrationsDir).filter((file) => file.endsWith('.sql')).sort();

// drizzle's Expo migrator looks migrations up by `m${idx padded to 4}`.
const entries = journal.entries.map((entry) => {
  const prefix = String(entry.idx).padStart(4, '0');
  const file = files.find((candidate) => candidate.startsWith(prefix));
  if (!file) {
    console.error(`Missing SQL file for migration ${entry.tag}`);
    process.exit(1);
  }
  return { key: `m${prefix}`, sql: readFileSync(join(migrationsDir, file), 'utf8'), tag: entry.tag };
});

const output = `// AUTO-GENERATED by scripts/build-migrations.mjs — do not edit by hand.
// Run \`npm run db:generate\` after changing src/db/schema.ts.
/* eslint-disable */

export const migrationJournal = ${JSON.stringify(journal, null, 2)} as const;

/** Keyed by \`m<idx>\` exactly as drizzle-orm's Expo migrator expects. */
export const migrationSql: Record<string, string> = {
${entries
  .map((entry) => `  // ${entry.tag}\n  '${entry.key}': ${JSON.stringify(entry.sql)},`)
  .join('\n')}
};

export default { journal: migrationJournal, migrations: migrationSql };
`;

writeFileSync(join(root, 'src', 'db', 'migrations-bundle.ts'), output, 'utf8');
console.log(`Wrote src/db/migrations-bundle.ts with ${entries.length} migration(s).`);
